void drawBitmapText(FrameBuffer& frameBuffer, const std::string& text, int x, int y, int pixelScale, Color color) {
    const auto& table = glyphTable();
    int cursorX = x;
    for (char character : text) {
        const auto glyph = table.find(static_cast<char>(std::toupper(static_cast<unsigned char>(character))));
        if (glyph != table.end()) {
            // Each "on" font pixel becomes a pixelScale x pixelScale block.
            for (int row = 0; row < glyphRows; ++row) {
                for (int column = 0; column < glyphColumns; ++column) {
                    if (glyph->second[row][column] != '1') continue;
                    for (int blockY = 0; blockY < pixelScale; ++blockY) {
                        const int screenY = y + row * pixelScale + blockY;
                        const int screenX = cursorX + column * pixelScale;
                        frameBuffer.fillSpan(screenY, screenX, screenX + pixelScale - 1, color);
                    }
                }
            }
        }
        cursorX += (glyphColumns + glyphSpacing) * pixelScale;
    }
}

int measureBitmapText(const std::string& text, int pixelScale) {
    if (text.empty()) return 0;
    return static_cast<int>(text.size()) * (glyphColumns + glyphSpacing) * pixelScale - glyphSpacing * pixelScale;
}
